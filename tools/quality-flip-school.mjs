import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import {auditUrl,launchAuditBrowser} from './quality-browser-runtime.mjs';
import {FLIP_LESSONS} from '../src/game/FlipLessons.js';
const out=process.env.FLIP_ARTIFACT_DIR||'artifacts/flip-school';await mkdir(out,{recursive:true});
const report={url:auditUrl,checks:[],clips:[],errors:[]};
const browser=await launchAuditBrowser();
try{
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  await context.addInitScript(()=>{
    window.schoolPad={connected:true,id:'Flip School QA',axes:[0,0,0,0],buttons:Array.from({length:17},()=>({pressed:false,value:0}))};
    Object.defineProperty(navigator,'getGamepads',{value:()=>[window.schoolPad]});
  });
  const page=await context.newPage();page.on('pageerror',error=>report.errors.push(error.message));
  await page.goto(auditUrl);
  await page.waitForFunction(()=>window.streetSkate?.ready,null,{timeout:90000});
  await page.locator('[data-action="flipSchool"]').click();
  await page.locator('body[data-screen="flipSchool"]').waitFor();
  assert.equal(await page.locator('.flip-steps').evaluate(el=>el.parentElement.className),'flip-lesson-detail');
  const video=page.locator('[data-flip-video]');
  for(const [index,lesson] of FLIP_LESSONS.entries()){
    if(index)await page.locator(`[data-action="flipLesson"][data-index="${index}"]`).click();
    await page.waitForFunction(()=>{const v=document.querySelector('video');return v?.readyState>=2&&Number.isFinite(v.duration);});
    assert.equal(await page.locator('video').count(),1);
    assert.equal(await video.evaluate(v=>v.playbackRate),.5);
    const metadata=await video.evaluate(v=>({duration:v.duration,width:v.videoWidth,height:v.videoHeight,src:v.currentSrc}));
    assert.ok(metadata.duration>2.8&&metadata.duration<3.6);
    assert.equal(metadata.width,960);assert.ok(metadata.src.endsWith(lesson.id+'.webm'));
    report.clips.push({trick:lesson.trick.name,...metadata});
    await video.evaluate(v=>{v.pause();v.currentTime=1.20;});
    await page.waitForFunction(()=>document.querySelector('[data-pad="flip"]')?.classList.contains('is-active'));
    assert.equal(await page.locator('.flip-steps [aria-current="step"] b').textContent(),'Flick');
  }
  report.checks.push('All eight clips decode; timed flip and direction cues agree with the video');
  await page.locator('[data-action="flipInput"][data-index="1"]').click();
  assert.ok((await page.locator('.flip-steps').textContent()).includes('Square'));
  await page.locator('[data-action="flipInput"][data-index="2"]').click();
  assert.ok((await page.locator('.flip-steps').textContent()).includes('S + D + ← arrow'));
  await page.screenshot({path:`${out}/keyboard.png`});
  await page.locator('[data-action="flipInput"][data-index="0"]').click();
  await page.locator('[data-action="flipLesson"][data-index="4"]').click();
  await page.waitForFunction(()=>document.querySelector('video')?.readyState>=2);
  await video.evaluate(v=>{v.pause();v.currentTime=1.35;});
  await page.waitForTimeout(100);
  await page.screenshot({path:`${out}/desktop.png`});
  const paused=await video.evaluate(v=>v.currentTime);
  await page.waitForTimeout(250);assert.equal(await video.evaluate(v=>v.currentTime),paused);
  await page.locator('[data-action="flipSpeed"]').click();assert.equal(await video.evaluate(v=>v.playbackRate),1);
  await page.locator('[data-action="flipReplay"]').click();
  await page.waitForFunction(()=>document.querySelector('video').currentTime<.6);
  await page.waitForFunction(()=>document.querySelector('video').currentTime>2.8);
  await page.waitForFunction(()=>document.querySelector('video').currentTime<.6);
  report.checks.push('Xbox/PlayStation/keyboard labels, pause, replay, speed and looping work');
  for(const [width,height]of[[1920,1080],[1280,720],[1280,600]]){
    await page.setViewportSize({width,height});
    assert.equal(await page.locator('.shell-content').evaluate(el=>el.scrollWidth>el.clientWidth+1),false);
    await page.locator('[data-action="flipPlay"]').scrollIntoViewIfNeeded();
    await page.screenshot({path:`${out}/desktop-${width}x${height}.png`});
  }
  await page.locator('[data-action="flipLesson"][data-index="0"]').focus();
  await page.keyboard.press('ArrowDown');await page.keyboard.press('Enter');
  assert.equal(await page.locator('.flip-detail-heading h3').textContent(),'Heelflip');
  await page.evaluate(()=>{window.schoolPad.buttons[13]={pressed:true,value:1};});
  await page.waitForFunction(()=>document.activeElement?.dataset.action==='flipLesson'&&document.activeElement?.dataset.index==='2');
  await page.evaluate(()=>{window.schoolPad.buttons[13]={pressed:false,value:0};});
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  await page.evaluate(()=>{window.schoolPad.buttons[0]={pressed:true,value:1};});
  await page.waitForFunction(()=>document.querySelector('.flip-detail-heading h3')?.textContent==='Impossible');
  await page.evaluate(()=>{window.schoolPad.buttons[0]={pressed:false,value:0};});
  await page.evaluate(()=>{window.schoolPad.buttons[1]={pressed:true,value:1};});
  await page.locator('body[data-screen="title"]').waitFor();
  await page.evaluate(()=>{window.schoolPad.buttons[1]={pressed:false,value:0};});
  assert.equal(await page.locator('video').count(),0);
  await page.locator('[data-action="tutorial"]').click();
  await page.locator('[data-action="next"]').click();await page.locator('[data-action="next"]').click();
  await page.locator('[data-action="flipSchool"]').focus();await page.keyboard.press('Enter');
  await page.locator('body[data-screen="flipSchool"]').waitFor();await page.keyboard.press('Escape');
  await page.locator('body[data-screen="tutorial"]').waitFor();
  assert.ok((await page.locator('.tutorial-frame h2').textContent()).includes('Flip tricks'));
  report.checks.push('Desktop layouts, keyboard selection, gamepad Back, disposal and return to tutorial');
  await page.keyboard.press('Escape');await page.locator('[data-action="flipSchool"]').click();
  await page.locator('[data-action="practice"]').click();
  await page.locator('body[data-screen="select"]').waitFor();
  await page.locator('[data-action="hero"][data-index="0"]').click();
  await page.locator('[data-action="board"][data-index="6"]').click();
  await page.locator('[data-action="confirmLoadout"]').click();
  await page.locator('body[data-screen="playing"]').waitFor({timeout:90000});
  await page.keyboard.press('Escape');await page.locator('[data-action="flipSchool"]').click();
  const before=await page.evaluate(()=>window.streetSkate.skater.position.toArray());
  await page.waitForTimeout(400);
  assert.deepEqual(await page.evaluate(()=>window.streetSkate.skater.position.toArray()),before);
  await page.keyboard.press('Escape');await page.locator('[data-action="resume"]').click();
  await page.locator('body[data-screen="playing"]').waitFor();
  report.checks.push('Free Practice opens a real session; opening lessons pauses gameplay and returning resumes');
  const reduced=await context.newPage();await reduced.emulateMedia({reducedMotion:'reduce'});
  await reduced.goto(auditUrl);await reduced.locator('[data-action="flipSchool"]').click();
  await reduced.waitForFunction(()=>document.querySelector('video')?.readyState>=2);
  assert.equal(await reduced.locator('video').evaluate(v=>v.paused),true);await reduced.close();
  const failure=await context.newPage();await failure.route('**/flip-school/*.webm',route=>route.fulfill({status:404,body:'missing test clip'}));
  await failure.goto(auditUrl);await failure.locator('[data-action="flipSchool"]').click();
  await failure.locator('[data-video-error]').waitFor({state:'visible'});
  assert.equal(await failure.locator('.flip-steps li').count(),4);await failure.close();
  report.checks.push('Reduced motion starts paused; missing video retains readable instructions');
  assert.deepEqual(report.errors,[]);report.result='PASS';
}catch(error){report.result='FAIL';report.error=String(error.stack||error);process.exitCode=1;console.error(error);}
finally{await writeFile(`${out}/report.json`,JSON.stringify(report,null,2));await browser.close();console.log(JSON.stringify(report));}
