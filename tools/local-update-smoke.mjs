import assert from 'node:assert/strict';
import {launchAuditBrowser} from './quality-browser-runtime.mjs';
const browser=await launchAuditBrowser();
try {
  const page=await browser.newPage({viewport:{width:1280,height:720}});
  await page.addInitScript(()=>{
    window.testPad={connected:true,index:0,id:'QA controller',axes:[0,0,0,0],buttons:Array.from({length:17},()=>({pressed:false,value:0}))};
    Object.defineProperty(navigator,'getGamepads',{value:()=>[window.testPad]});
  });
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:5182/');
  await page.waitForFunction(()=>window.streetSkate?.ready,null,{timeout:90000});
  await page.locator('[data-action="tutorial"]').click();
  await page.locator('[data-action="tutorialNext"]').click();
  await page.locator('[data-action="next"]').focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('body').getAttribute('data-screen'),'tutorial');
  await page.keyboard.press('Escape');
  await page.locator('[data-action="options"]').click();
  assert.match(await page.locator('[data-action="deadZone"]').textContent(),/16%/);
  await page.locator('[data-action="deadZone"]').click();
  assert.match(await page.locator('[data-action="deadZone"]').textContent(),/24%/);
  assert.equal(await page.evaluate(()=>localStorage.getItem('streetskate.stickDeadZone')),'0.24');
  await page.locator('[data-action="graphicsMenu"]').click();
  const smoothing=page.locator('[data-action="edgeToggle"]');
  assert.equal(await smoothing.getAttribute('aria-pressed'),'false');
  await smoothing.click();assert.equal(await smoothing.getAttribute('aria-pressed'),'true');
  assert.equal(await page.evaluate(()=>window.streetSkate.graphicsStatus().msaaSamples),2);
  await smoothing.click();assert.equal(await smoothing.getAttribute('aria-pressed'),'false');
  await page.locator('[data-action="back"]').click();
  await page.locator('[data-action="back"]').click();
  await page.locator('[data-action="practice"]').click();
  await page.locator('[data-action="hero"][data-index="0"]').click();
  await page.locator('[data-action="board"][data-index="6"]').click();
  await page.locator('[data-action="confirmLoadout"]').click();
  await page.locator('body[data-screen="playing"]').waitFor({timeout:90000});
  await page.waitForTimeout(500);
  await page.evaluate(()=>{window.testPad.axes[0]=.20;});
  await page.waitForFunction(()=>window.streetSkate.captureInput().steer===0);
  await page.evaluate(()=>{window.testPad.axes[0]=.7;});
  await page.waitForFunction(()=>window.streetSkate.captureInput().steer>.5);
  await page.evaluate(()=>{window.testPad.axes[0]=0;});
  await page.keyboard.press('m');
  await page.waitForFunction(()=>window.streetSkate.skater.feedback.includes('MARKER SAVED'));
  const before=await page.evaluate(()=>window.streetSkate.skater.position.toArray());
  await page.waitForTimeout(900);await page.keyboard.press('n');
  await page.waitForFunction(()=>window.streetSkate.skater.feedback.includes('RETURNED TO MARKER'));
  const after=await page.evaluate(()=>window.streetSkate.skater.position.toArray());
  assert.ok(Math.hypot(...after.map((v,i)=>v-before[i]))<2,'return is close to marker');
  await page.evaluate(()=>{for(const i of [4,5,12])window.testPad.buttons[i]={pressed:true,value:1};});
  await page.waitForFunction(()=>window.streetSkate.skater.feedback.includes('MARKER SAVED'));
  await page.evaluate(()=>{for(const i of [4,5,12])window.testPad.buttons[i]={pressed:false,value:0};});
  await page.waitForTimeout(100);
  await page.evaluate(()=>{for(const i of [4,5,13])window.testPad.buttons[i]={pressed:true,value:1};});
  await page.waitForFunction(()=>window.streetSkate.skater.feedback.includes('RETURNED TO MARKER'));
  await page.evaluate(()=>{for(const i of [4,5,13])window.testPad.buttons[i]={pressed:false,value:0};});
  await page.keyboard.press('Escape');
  await page.locator('[data-action="practiceDrills"]').click();
  await page.locator('[data-action="practiceInputs"]').click();
  await page.locator('[data-action="resume"]').click();
  await page.locator('.practice-drill').waitFor({state:'visible'});
  assert.match(await page.locator('.practice-drill').textContent(),/Land an ollie/);
  await page.keyboard.down('Space');
  await page.waitForFunction(()=>document.querySelector('.practice-input').textContent.includes('CHARGE'));
  await page.waitForTimeout(220);await page.keyboard.up('Space');
  await page.waitForFunction(()=>document.querySelector('.practice-drill').textContent.includes('kickflip'),null,{timeout:12000});
  await page.screenshot({path:'artifacts/local-update/practice-drills.png'});
  assert.deepEqual(errors,[]);console.log('PASS tutorial, practice marker, and banked practice drill');
} finally {await browser.close();}
